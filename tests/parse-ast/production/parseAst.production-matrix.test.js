/** Validates the parser against a realistic cross-dialect production corpus. */
import { describe, expect, it } from 'vitest';
import { parseAST } from '@/lib/parse-ast/parseAst.js';

const errorsOnly = (errors) => errors.filter((error) => error.severity === 'error');
const stripSchema = (name) => {
    if (!name) return name;
    const dot = name.lastIndexOf('.');
    return dot >= 0 ? name.slice(dot + 1) : name;
};

function parse(sql) {
    const result = parseAST(sql);
    return {
        ...result,
        errorsOnly: () => errorsOnly(result.errors),
        table: (name) => result.ast.tables.find((table) => stripSchema(table.name).toLowerCase() === name.toLowerCase()),
        column: (tableName, columnName) => {
            const table = result.ast.tables.find((item) => stripSchema(item.name).toLowerCase() === tableName.toLowerCase());
            return table?.columns.find((column) => column.name.toLowerCase() === columnName.toLowerCase());
        },
        type: (name) => result.ast.types.find((type) => stripSchema(type.name).toLowerCase() === name.toLowerCase()),
        index: (name) => result.ast.indexes.find((index) => index.name === name),
    };
}

const fkActions = [
    'ON DELETE CASCADE ON UPDATE CASCADE',
    'ON DELETE RESTRICT ON UPDATE NO ACTION',
    'ON DELETE SET NULL ON UPDATE SET DEFAULT',
    'ON DELETE NO ACTION ON UPDATE CASCADE',
    'ON UPDATE CASCADE ON DELETE CASCADE',
];

const sqliteCases = Array.from({ length: 30 }, (_, i) => {
    const suffix = i.toString().padStart(2, '0');
    const tableOption = ['STRICT', 'WITHOUT ROWID', 'STRICT, WITHOUT ROWID'][i % 3];
    const generatedMode = i % 2 === 0 ? 'STORED' : 'VIRTUAL';
    const action = fkActions[i % fkActions.length];
    return {
        name: `SQLite production syntax ${suffix}`,
        parent: `catalog_${suffix}`,
        child: `stock_moves_${suffix}`,
        index: `idx_stock_moves_${suffix}`,
        sql: `
            CREATE TABLE "catalog_${suffix}" (
                tenant_id TEXT NOT NULL,
                sku TEXT NOT NULL,
                name TEXT COLLATE NOCASE NOT NULL,
                price REAL NOT NULL CHECK (price >= 0),
                price_bucket TEXT GENERATED ALWAYS AS (
                    CASE WHEN price >= ${100 + i} THEN 'premium' ELSE 'standard' END
                ) ${generatedMode},
                PRIMARY KEY (tenant_id, sku)
            ) ${tableOption};

            CREATE TABLE "stock_moves_${suffix}" (
                move_id INTEGER PRIMARY KEY AUTOINCREMENT,
                tenant_id TEXT NOT NULL,
                sku TEXT NOT NULL,
                delta INTEGER NOT NULL CHECK (delta <> 0),
                reason TEXT DEFAULT 'manual',
                FOREIGN KEY (tenant_id, sku)
                    REFERENCES "catalog_${suffix}"(tenant_id, sku)
                    ${action}
            ) STRICT;

            CREATE INDEX idx_stock_moves_${suffix}
                ON "stock_moves_${suffix}" (tenant_id, sku, delta)
                WHERE delta <> 0;
        `,
    };
});

const postgresCases = Array.from({ length: 30 }, (_, i) => {
    const suffix = i.toString().padStart(2, '0');
    const identity = i % 2 === 0 ? 'GENERATED ALWAYS AS IDENTITY' : `GENERATED BY DEFAULT AS IDENTITY (START WITH ${100 + i} INCREMENT BY ${i + 1})`;
    const tableOption = ['PARTITION BY LIST (tenant_id)', 'WITH (fillfactor=70)', 'TABLESPACE pg_default'][i % 3];
    const indexMethod = ['btree', 'gin', 'hash'][i % 3];
    return {
        name: `PostgreSQL production syntax ${suffix}`,
        enumName: `state_${suffix}`,
        compositeName: `dimensions_${suffix}`,
        table: `products_${suffix}`,
        child: `product_events_${suffix}`,
        index: `idx_products_${suffix}`,
        sql: `
            CREATE TYPE warehouse.state_${suffix} AS ENUM ('draft', 'active', 'deleted');
            CREATE TYPE warehouse.dimensions_${suffix} AS (
                width NUMERIC(10, 2),
                height NUMERIC(10, 2),
                depth NUMERIC(10, 2)
            );

            CREATE TABLE warehouse.products_${suffix} (
                tenant_id BIGINT NOT NULL,
                product_id BIGINT ${identity},
                sku TEXT NOT NULL,
                state warehouse.state_${suffix} NOT NULL DEFAULT 'draft',
                dims warehouse.dimensions_${suffix},
                metadata JSONB NOT NULL DEFAULT jsonb_build_object('source', 'matrix'),
                search_text TSVECTOR GENERATED ALWAYS AS (to_tsvector('simple', sku)) STORED,
                PRIMARY KEY (tenant_id, product_id),
                CONSTRAINT uq_products_${suffix}_sku UNIQUE (tenant_id, sku),
                CONSTRAINT chk_products_${suffix}_state CHECK (state <> 'deleted' OR metadata IS NOT NULL)
            ) ${tableOption};

            CREATE TABLE warehouse.product_events_${suffix} (
                tenant_id BIGINT NOT NULL,
                product_id BIGINT NOT NULL,
                event_no BIGINT NOT NULL,
                payload JSONB,
                CONSTRAINT fk_product_events_${suffix}
                    FOREIGN KEY (tenant_id, product_id)
                    REFERENCES warehouse.products_${suffix}(tenant_id, product_id)
                    DEFERRABLE INITIALLY DEFERRED,
                PRIMARY KEY (tenant_id, product_id, event_no)
            );

            CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_products_${suffix}
                ON ONLY warehouse.products_${suffix} USING ${indexMethod} (state, sku)
                WHERE state <> 'deleted';
        `,
    };
});

const mysqlCases = Array.from({ length: 30 }, (_, i) => {
    const suffix = i.toString().padStart(2, '0');
    const generatedMode = i % 2 === 0 ? 'STORED' : 'VIRTUAL';
    const engine = ['InnoDB', 'MyISAM', 'NDB'][i % 3];
    return {
        name: `MySQL production syntax ${suffix}`,
        parent: `shops_${suffix}`,
        child: `shop_products_${suffix}`,
        fulltextIndex: `ft_shops_${suffix}`,
        priceIndex: `idx_products_${suffix}_price`,
        sql: `
            CREATE TABLE \`shops_${suffix}\` (
                \`id\` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
                \`slug\` VARCHAR(80) NOT NULL,
                \`status\` ENUM('draft','open','closed') NOT NULL DEFAULT 'draft',
                \`features\` SET('pos','online','pickup') DEFAULT 'online',
                \`search_blob\` TEXT,
                PRIMARY KEY (\`id\`),
                UNIQUE KEY \`uk_shops_${suffix}_slug\` (\`slug\`),
                FULLTEXT KEY \`ft_shops_${suffix}\` (\`search_blob\`)
            ) ENGINE=${engine} DEFAULT CHARSET=utf8mb4 ROW_FORMAT=DYNAMIC;

            CREATE TABLE \`shop_products_${suffix}\` (
                \`shop_id\` BIGINT UNSIGNED NOT NULL,
                \`sku\` VARCHAR(64) NOT NULL,
                \`price\` DECIMAL(10, 2) NOT NULL,
                \`tax_rate\` DECIMAL(5, 4) NOT NULL DEFAULT 0.0000,
                \`gross_price\` DECIMAL(10, 2)
                    GENERATED ALWAYS AS (\`price\` + (\`price\` * \`tax_rate\`)) ${generatedMode},
                PRIMARY KEY (\`shop_id\`, \`sku\`),
                CONSTRAINT \`fk_products_${suffix}_shop\`
                    FOREIGN KEY (\`shop_id\`) REFERENCES \`shops_${suffix}\` (\`id\`) ON DELETE CASCADE,
                KEY \`idx_products_${suffix}_price\` (\`price\`, \`gross_price\`)
            ) ENGINE=InnoDB;
        `,
    };
});

const mssqlCases = Array.from({ length: 30 }, (_, i) => {
    const suffix = i.toString().padStart(2, '0');
    const computedTail = i % 2 === 0 ? 'PERSISTED NOT NULL' : 'NOT NULL PERSISTED';
    const indexKind = i % 2 === 0 ? 'CLUSTERED' : 'NONCLUSTERED';
    return {
        name: `MSSQL production syntax ${suffix}`,
        parent: `Invoices_${suffix}`,
        child: `InvoiceLines_${suffix}`,
        index: `IX_Lines_${suffix}_Sku`,
        sql: `
            CREATE TABLE [sales].[Invoices_${suffix}] (
                [InvoiceID] BIGINT IDENTITY(${100 + i}, ${i + 1}) NOT NULL,
                [CustomerCode] NVARCHAR(40) NOT NULL,
                [Subtotal] DECIMAL(19, 4) NOT NULL,
                [Tax] DECIMAL(19, 4) NOT NULL DEFAULT 0,
                [Total] AS ([Subtotal] + [Tax]) ${computedTail},
                CONSTRAINT [PK_Invoices_${suffix}] PRIMARY KEY ${indexKind} ([InvoiceID]),
                CONSTRAINT [UQ_Invoices_${suffix}_Customer] UNIQUE NONCLUSTERED ([CustomerCode])
            );
            GO

            CREATE TABLE [sales].[InvoiceLines_${suffix}] (
                [InvoiceID] BIGINT NOT NULL,
                [LineNo] INT NOT NULL,
                [Sku] NVARCHAR(64) NOT NULL,
                [Qty] INT NOT NULL,
                [UnitPrice] DECIMAL(19, 4) NOT NULL,
                [LineTotal] AS [Qty] * [UnitPrice] PERSISTED,
                CONSTRAINT [PK_InvoiceLines_${suffix}] PRIMARY KEY NONCLUSTERED ([InvoiceID], [LineNo]),
                CONSTRAINT [FK_Lines_${suffix}_Invoice]
                    FOREIGN KEY ([InvoiceID]) REFERENCES [sales].[Invoices_${suffix}]([InvoiceID])
            );

            CREATE NONCLUSTERED INDEX [IX_Lines_${suffix}_Sku]
                ON [sales].[InvoiceLines_${suffix}] ([Sku], [InvoiceID])
                INCLUDE ([Qty], [UnitPrice])
                WHERE [Qty] > 0;
        `,
    };
});

describe.each([
    ['SQLite', sqliteCases],
    ['PostgreSQL', postgresCases],
    ['MySQL', mysqlCases],
    ['MSSQL', mssqlCases],
])('parseAST production matrix - %s', (_dialect, cases) => {
    it.each(cases)('$name', (testCase) => {
        const result = parse(testCase.sql);
        expect(result.errorsOnly()).toEqual([]);

        if (testCase.parent && testCase.child) {
            expect(result.table(testCase.parent)).toBeTruthy();
            expect(result.table(testCase.child)).toBeTruthy();
        }
        if (testCase.table && testCase.child) {
            expect(result.table(testCase.table)).toBeTruthy();
            expect(result.table(testCase.child)).toBeTruthy();
        }

        if (testCase.enumName) {
            expect(result.type(testCase.enumName).values).toHaveLength(3);
            expect(result.type(testCase.compositeName).fields).toHaveLength(3);
        }

        if (testCase.name.startsWith('SQLite')) {
            expect(result.column(testCase.parent, 'price_bucket').generated).toMatch(/GENERATED ALWAYS AS/i);
            expect(result.column(testCase.child, 'move_id').autoIncrement).toBe(true);
            expect(result.index(testCase.index).columns).toEqual(['tenant_id', 'sku', 'delta']);
        } else if (testCase.name.startsWith('PostgreSQL')) {
            expect(result.column(testCase.table, 'product_id').autoIncrement).toBe(true);
            expect(result.column(testCase.table, 'search_text').generated).toMatch(/to_tsvector/i);
            expect(result.index(testCase.index).columns).toEqual(['state', 'sku']);
        } else if (testCase.name.startsWith('MySQL')) {
            expect(result.column(testCase.parent, 'id').autoIncrement).toBe(true);
            expect(result.column(testCase.parent, 'status').type).toBe('status_enum');
            expect(result.column(testCase.parent, 'features').type).toBe('features_set');
            expect(result.column(testCase.child, 'gross_price').generated).toMatch(/GENERATED ALWAYS AS/i);
            expect(result.index(testCase.fulltextIndex).kind).toBe('fulltext');
            expect(result.index(testCase.priceIndex).columns).toEqual(['price', 'gross_price']);
        } else {
            expect(result.column(testCase.parent, 'InvoiceID').autoIncrement).toBe(true);
            expect(result.column(testCase.parent, 'Total').type).toBe('COMPUTED');
            expect(result.column(testCase.child, 'LineTotal').generated).toMatch(/PERSISTED/);
            expect(result.index(testCase.index).columns).toEqual(['Sku', 'InvoiceID']);
        }
    });
});
