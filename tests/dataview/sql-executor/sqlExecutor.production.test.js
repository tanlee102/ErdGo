// ═══════════════ SQLite DDL ═══════════════
describe('SQLite DDL production', () => {
    it('INTEGER PRIMARY KEY acts as ROWID autoincrement', () => {
        const r = exec(`
            CREATE TABLE t (id INTEGER PRIMARY KEY, name TEXT);
            INSERT INTO t (name) VALUES ('a');
            INSERT INTO t (name) VALUES ('b');
        `, { dialect: 'sqlite' });
        expect(r.errors()).toHaveLength(0);
    });
    it('CREATE TABLE IF NOT EXISTS is idempotent', () => {
        const r = exec(`
            CREATE TABLE IF NOT EXISTS t (id INT PRIMARY KEY);
            CREATE TABLE IF NOT EXISTS t (id INT PRIMARY KEY);
            INSERT INTO t VALUES (1);
        `);
        expect(r.errors()).toHaveLength(0);
        expect(r.rowsOf('t')).toHaveLength(1);
    });
    it('DROP TABLE IF EXISTS + recreate', () => {
        const r = exec(`
            CREATE TABLE t (id INT PRIMARY KEY);
            INSERT INTO t VALUES (1);
            DROP TABLE IF EXISTS t;
            CREATE TABLE t (id INT PRIMARY KEY, name TEXT);
            INSERT INTO t VALUES (2, 'new');
        `);
        expect(r.rowsOf('t')).toHaveLength(1);
        expect(r.rowsOf('t')[0].id).toBe(2);
    });
    it('GENERATED ALWAYS AS with VIRTUAL', () => {
        const r = exec(`
            CREATE TABLE t (id INT PRIMARY KEY, a INT, b INT,
                sum_val INT GENERATED ALWAYS AS (a + b) VIRTUAL);
            INSERT INTO t (id, a, b) VALUES (1, 10, 20);
        `);
        expect(r.rowsOf('t')[0].sum_val).toBe(30);
    });
});

// ═══════════════ Cross-dialect DML ═══════════════
describe('Cross-dialect DML production', () => {
    it('multi-row INSERT', () => {
        const r = exec(`
            CREATE TABLE t (id INT PRIMARY KEY, name TEXT);
            INSERT INTO t VALUES (1, 'a'), (2, 'b'), (3, 'c'), (4, 'd');
        `);
        expect(r.rowsOf('t')).toHaveLength(4);
    });
    it('INSERT with DEFAULT keyword', () => {
        const r = exec(`
            CREATE TABLE t (id SERIAL PRIMARY KEY, status TEXT DEFAULT 'active');
            INSERT INTO t (status) VALUES (DEFAULT);
            INSERT INTO t (status) VALUES ('inactive');
        `);
        expect(r.rowsOf('t')[0].status).toBe('active');
        expect(r.rowsOf('t')[1].status).toBe('inactive');
    });
    it('UPDATE SET multiple columns', () => {
        const r = exec(`
            CREATE TABLE t (id INT PRIMARY KEY, a TEXT, b TEXT);
            INSERT INTO t VALUES (1, 'old_a', 'old_b');
            UPDATE t SET a = 'new_a', b = 'new_b' WHERE id = 1;
        `);
        const row = r.rowsOf('t')[0];
        expect(row.a).toBe('new_a');
        expect(row.b).toBe('new_b');
    });
    it('DELETE with WHERE', () => {
        const r = exec(`
            CREATE TABLE t (id INT PRIMARY KEY, name TEXT);
            INSERT INTO t VALUES (1, 'a'), (2, 'b'), (3, 'c');
            DELETE FROM t WHERE id = 2;
        `);
        expect(r.rowsOf('t')).toHaveLength(2);
        expect(r.rowsOf('t').find(r => r.id === 2)).toBeUndefined();
    });
    it('ALTER TABLE ADD COLUMN + populate', () => {
        const r = exec(`
            CREATE TABLE t (id INT PRIMARY KEY);
            INSERT INTO t VALUES (1);
            ALTER TABLE t ADD COLUMN name TEXT;
            UPDATE t SET name = 'Alice' WHERE id = 1;
        `);
        expect(r.rowsOf('t')[0].name).toBe('Alice');
    });
    it('FK reference recognized', () => {
        const r = exec(`
            CREATE TABLE parent (id INT PRIMARY KEY);
            CREATE TABLE child (id INT PRIMARY KEY, parent_id INT REFERENCES parent(id));
        `);
        const col = r.col('child', 'parent_id');
        expect(col.fk).toBe(true);
        expect(col.refTable).toBe('parent');
    });
    it('composite UNIQUE via ALTER TABLE', () => {
        const r = exec(`
            CREATE TABLE t (a INT, b INT, v TEXT);
            ALTER TABLE t ADD CONSTRAINT uq UNIQUE (a, b);
            INSERT INTO t VALUES (1, 1, 'first');
            INSERT INTO t VALUES (1, 2, 'second');
            INSERT INTO t VALUES (1, 1, 'duplicate');
        `);
        expect(r.errors().length).toBeGreaterThan(0);
        expect(r.rowsOf('t')).toHaveLength(2);
    });
    it('INSERT with subquery in VALUES', () => {
        const r = exec(`
            CREATE TABLE cats (id INT PRIMARY KEY, name TEXT);
            INSERT INTO cats VALUES (1, 'A'), (2, 'B');
            CREATE TABLE items (id INT PRIMARY KEY, cat_id INT);
            INSERT INTO items VALUES (1, (SELECT id FROM cats WHERE name = 'B'));
        `);
        expect(r.rowsOf('items')[0].cat_id).toBe(2);
    });
    it('GENERATED column recalculated on UPDATE', () => {
        const r = exec(`
            CREATE TABLE t (id INT PRIMARY KEY, a NUMERIC, b NUMERIC,
                product NUMERIC GENERATED ALWAYS AS (a * b) STORED);
            INSERT INTO t (id, a, b) VALUES (1, 5, 10);
            UPDATE t SET a = 20 WHERE id = 1;
        `);
        expect(r.rowsOf('t')[0].product).toBe(200);
    });
});

// ═══════════════ Full E2E: Multi-table Scenario ═══════════════
describe('E2E: multi-table production scenario', () => {
    it('complete e-commerce schema', () => {
        const r = exec(`
            CREATE TABLE customers (
                id SERIAL PRIMARY KEY,
                email VARCHAR(255) UNIQUE NOT NULL,
                name VARCHAR(100) NOT NULL
            );
            CREATE TABLE products (
                id SERIAL PRIMARY KEY,
                name VARCHAR(200) NOT NULL,
                price NUMERIC NOT NULL CHECK (price > 0)
            );
            CREATE TABLE orders (
                id SERIAL PRIMARY KEY,
                customer_id INT REFERENCES customers(id),
                total NUMERIC DEFAULT 0
            );
            CREATE TABLE order_items (
                id SERIAL PRIMARY KEY,
                order_id INT REFERENCES orders(id),
                product_id INT REFERENCES products(id),
                qty INT NOT NULL DEFAULT 1,
                line_total NUMERIC GENERATED ALWAYS AS (qty * 0) STORED
            );

            INSERT INTO customers (email, name) VALUES ('alice@test.com', 'Alice');
            INSERT INTO customers (email, name) VALUES ('bob@test.com', 'Bob');

            INSERT INTO products (name, price) VALUES ('Widget', 9.99);
            INSERT INTO products (name, price) VALUES ('Gadget', 24.99);
            INSERT INTO products (name, price) VALUES ('Doohickey', 4.99);

            INSERT INTO orders (customer_id, total) VALUES (1, 100);
            INSERT INTO orders (customer_id, total) VALUES (2, 50);

            INSERT INTO order_items (order_id, product_id, qty) VALUES (1, 1, 3);
            INSERT INTO order_items (order_id, product_id, qty) VALUES (1, 2, 1);
            INSERT INTO order_items (order_id, product_id, qty) VALUES (2, 3, 5);
        `);

        expect(r.errors()).toHaveLength(0);
        expect(r.rowsOf('customers')).toHaveLength(2);
        expect(r.rowsOf('products')).toHaveLength(3);
        expect(r.rowsOf('orders')).toHaveLength(2);
        expect(r.rowsOf('order_items')).toHaveLength(3);

        // FK references
        expect(r.col('orders', 'customer_id').refTable).toBe('customers');
        expect(r.col('order_items', 'order_id').refTable).toBe('orders');
        expect(r.col('order_items', 'product_id').refTable).toBe('products');

        // Auto-increment
        expect(r.rowsOf('customers')[0].id).toBe(1);
        expect(r.rowsOf('customers')[1].id).toBe(2);
    });
});
