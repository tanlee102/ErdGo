describe('MySQL DDL production', () => {
    it('AUTO_INCREMENT', () => {
        const r = exec(`
            CREATE TABLE t (id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(50));
            INSERT INTO t (name) VALUES ('a');
            INSERT INTO t (name) VALUES ('b');
        `);
        expect(r.rowsOf('t')[0].id).toBe(1);
        expect(r.rowsOf('t')[1].id).toBe(2);
    });
    it('ENUM type as column', () => {
        const r = exec(`
            CREATE TABLE t (id INT PRIMARY KEY, status ENUM('active','inactive','pending'));
            INSERT INTO t VALUES (1, 'active');
        `);
        expect(r.rowsOf('t')[0].status).toBe('active');
    });
    it('# comment line stripped', () => {
        const r = exec(`
            # This is a MySQL comment
            CREATE TABLE t (id INT PRIMARY KEY);
            INSERT INTO t VALUES (1);
        `);
        expect(r.errors()).toHaveLength(0);
        expect(r.rowsOf('t')).toHaveLength(1);
    });
    it('backtick-quoted identifiers', () => {
        const r = exec("CREATE TABLE `my-table` (`id` INT PRIMARY KEY, `full name` TEXT); INSERT INTO `my-table` VALUES (1, 'test');");
        expect(r.errors()).toHaveLength(0);
    });
    it('DEFAULT CURRENT_TIMESTAMP', () => {
        const r = exec(`
            CREATE TABLE t (id INT PRIMARY KEY, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
            INSERT INTO t (id) VALUES (1);
        `);
        const row = r.rowsOf('t')[0];
        expect(row.created_at).toBeTruthy();
    });
});

