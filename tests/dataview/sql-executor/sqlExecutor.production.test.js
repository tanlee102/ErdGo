import { describe, it, expect } from 'vitest';
import { createSqlExecutor } from '@/features/data-view/lib/sqlExecutor.js';

function exec(sql, options = {}) {
    const executor = createSqlExecutor(options);
    const result = executor.execute(sql);
    return {
        tables: result.tables,
        log: result.log,
        table: (n) => { for (const [,v] of result.tables) if (v.name.toLowerCase() === n.toLowerCase()) return v; return null; },
        col: (t, c) => { const tb = result.tables; for (const [,v] of tb) if (v.name.toLowerCase() === t.toLowerCase()) return v.columns.find(x => x.name.toLowerCase() === c.toLowerCase()) || null; return null; },
        rowsOf: (n) => { for (const [,v] of result.tables) if (v.name.toLowerCase() === n.toLowerCase()) return v.rows; return null; },
        errors: () => result.log.filter(l => l.type === 'error'),
        warnings: () => result.log.filter(l => l.type === 'warning'),
    };
}

describe('Data View unsupported syntax diagnostics', () => {
    it('reports unsupported PostgreSQL WHERE operators and does not apply UPDATE rows', () => {
        const r = exec(`
            CREATE TABLE documents (
                id INT PRIMARY KEY,
                payload JSONB,
                matched BOOLEAN DEFAULT FALSE
            );
            INSERT INTO documents (id, payload) VALUES
                (1, '{"region":"apac"}'::jsonb),
                (2, '{"region":"eu"}'::jsonb);
            UPDATE documents
            SET matched = TRUE
            WHERE payload @> '{"region":"apac"}'::jsonb;
        `, { dialect: 'postgres' });

        expect(r.errors()).toHaveLength(1);
        expect(r.errors()[0].message).toContain('Unsupported PostgreSQL operator @>');
        expect(r.errors()[0].message).toMatch(/line \d+, column \d+/);
        expect(r.errors()[0].position).toMatchObject({ line: 12 });
        expect(r.rowsOf('documents').map((row) => row.matched)).toEqual([false, false]);
    });
});

// ═══════════════ PostgreSQL DDL ═══════════════
describe('PostgreSQL DDL production', () => {
    it('SERIAL + BIGSERIAL auto-increment', () => {
        const r = exec(`
            CREATE TABLE t (id SERIAL PRIMARY KEY, big_id BIGSERIAL, name TEXT);
            INSERT INTO t (name) VALUES ('a');
            INSERT INTO t (name) VALUES ('b');
        `);
        expect(r.rowsOf('t')[0].id).toBe(1);
        expect(r.rowsOf('t')[1].id).toBe(2);
    });
    it('UUID DEFAULT gen_random_uuid()', () => {
        const r = exec(`
            CREATE TABLE t (id UUID DEFAULT gen_random_uuid() PRIMARY KEY, name TEXT);
            INSERT INTO t (name) VALUES ('test');
        `);
        const row = r.rowsOf('t')[0];
        expect(row.id).toBeTruthy();
        expect(row.id.length).toBeGreaterThan(30);
    });
    it('GENERATED ALWAYS AS IDENTITY', () => {
        const r = exec(`
            CREATE TABLE t (id INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, name TEXT);
            INSERT INTO t (name) VALUES ('a');
            INSERT INTO t (name) VALUES ('b');
        `);
        expect(r.rowsOf('t')[0].id).toBe(1);
        expect(r.rowsOf('t')[1].id).toBe(2);
    });
    it('GENERATED BY DEFAULT AS IDENTITY (START WITH 100)', () => {
        const r = exec(`
            CREATE TABLE t (id INT GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 10) PRIMARY KEY, name TEXT);
            INSERT INTO t (name) VALUES ('a');
            INSERT INTO t (name) VALUES ('b');
        `);
        expect(r.rowsOf('t')[0].id).toBe(100);
        expect(r.rowsOf('t')[1].id).toBe(110);
    });
    it('CHECK constraint parsed without error', () => {
        const r = exec(`
            CREATE TABLE t (id INT PRIMARY KEY, age INT CHECK (age >= 0));
            INSERT INTO t VALUES (1, 25);
        `);
        expect(r.errors()).toHaveLength(0);
        expect(r.rowsOf('t')[0].age).toBe(25);
    });
    it('GENERATED ALWAYS AS (expr) STORED computed column', () => {
        const r = exec(`
            CREATE TABLE t (id INT PRIMARY KEY, price NUMERIC, qty INT,
                total NUMERIC GENERATED ALWAYS AS (price * qty) STORED);
            INSERT INTO t (id, price, qty) VALUES (1, 25.50, 4);
        `);
        expect(r.rowsOf('t')[0].total).toBe(102);
    });
    it('schema-qualified table name', () => {
        const r = exec(`
            CREATE SCHEMA IF NOT EXISTS myapp;
            CREATE TABLE myapp.users (id INT PRIMARY KEY, name TEXT);
            INSERT INTO myapp.users VALUES (1, 'Alice');
        `);
        expect(r.rowsOf('users')).toHaveLength(1);
    });
});

