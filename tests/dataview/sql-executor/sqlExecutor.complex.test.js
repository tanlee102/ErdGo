/** Exercises complex multi-statement Data View execution scenarios. */
import { describe, expect, it } from 'vitest';
import { createSqlExecutor } from '@/features/data-view/lib/sqlExecutor.js';

function exec(sql) {
    const executor = createSqlExecutor();
    const result = executor.execute(sql);
    return {
        tables: result.tables,
        log: result.log,
        table(name) {
            for (const table of result.tables.values()) {
                if (table.name.toLowerCase() === name.toLowerCase()) return table;
            }
            return null;
        },
        rows(name) {
            return this.table(name)?.rows || [];
        },
        errors() {
            return result.log.filter((entry) => entry.type === 'error');
        },
        warnings() {
            return result.log.filter((entry) => entry.type === 'warning');
        },
    };
}

describe('Data View SQL executor - complex workflows', () => {
    it('executes identity defaults, generated columns, subquery inserts, ALTERs, and row expressions together', () => {
        const r = exec(`
            CREATE TABLE tenants (
                id INT GENERATED BY DEFAULT AS IDENTITY (START WITH 10 INCREMENT BY 5) PRIMARY KEY,
                slug TEXT UNIQUE NOT NULL,
                active BOOLEAN NOT NULL DEFAULT true
            );
            INSERT INTO tenants (slug) VALUES ('acme'), ('globex');

            CREATE TABLE accounts (
                tenant_id INT NOT NULL REFERENCES tenants(id),
                account_no TEXT NOT NULL,
                name TEXT NOT NULL,
                balance NUMERIC NOT NULL DEFAULT 0,
                PRIMARY KEY (tenant_id, account_no),
                UNIQUE (tenant_id, name)
            );
            CREATE INDEX idx_accounts_name ON accounts (name);
            INSERT INTO accounts VALUES
                (10, 'cash', 'Cash', 1000),
                (10, 'ar', 'Receivables', DEFAULT),
                (15, 'cash', 'Cash', 250);

            CREATE TABLE entries (
                id INT GENERATED ALWAYS AS IDENTITY (START WITH 100 INCREMENT BY 10) PRIMARY KEY,
                tenant_id INT NOT NULL,
                account_no TEXT NOT NULL,
                debit NUMERIC DEFAULT 0,
                credit NUMERIC DEFAULT 0,
                signed_amount NUMERIC GENERATED ALWAYS AS (COALESCE(debit, 0) - COALESCE(credit, 0)) STORED,
                CONSTRAINT fk_entries_account FOREIGN KEY (tenant_id, account_no) REFERENCES accounts(tenant_id, account_no)
            );
            INSERT INTO entries (tenant_id, account_no, debit, credit) VALUES
                ((SELECT id FROM tenants WHERE slug = 'acme'), 'cash', 300, 0),
                ((SELECT id FROM tenants WHERE slug = 'acme'), 'ar', 0, 125),
                ((SELECT id FROM tenants WHERE slug = 'globex'), 'cash', DEFAULT, 75);

            UPDATE accounts SET balance = balance + 50 WHERE tenant_id = 10 AND account_no = 'cash';
            ALTER TABLE accounts RENAME COLUMN name TO display_name;
            ALTER TABLE accounts ADD COLUMN archived BOOLEAN DEFAULT false;
        `);

        expect(r.errors()).toEqual([]);
        expect(r.warnings()).toEqual([]);
        expect(r.rows('tenants').map((row) => row.id)).toEqual([10, 15]);

        const acmeCash = r.rows('accounts').find((row) => row.tenant_id === 10 && row.account_no === 'cash');
        expect(acmeCash.balance).toBe(1050);
        expect(acmeCash.display_name).toBe('Cash');
        expect(acmeCash.archived).toBe(false);
        expect(r.table('accounts').columns.map((column) => column.name)).toContain('display_name');
        expect(r.table('accounts').indexes.map((index) => index.name)).toContain('idx_accounts_name');

        expect(r.rows('entries').map((row) => row.id)).toEqual([100, 110, 120]);
        expect(r.rows('entries').map((row) => row.signed_amount)).toEqual([300, -125, -75]);
    });

    it('evaluates UPDATE expressions per matching row and leaves non-matching rows untouched', () => {
        const r = exec(`
            CREATE TABLE scores (
                id INT PRIMARY KEY,
                bucket TEXT,
                score INT,
                adjusted INT GENERATED ALWAYS AS (score * 2) STORED
            );
            INSERT INTO scores VALUES (1, 'a', 10, DEFAULT), (2, 'a', 20, DEFAULT), (3, 'b', 30, DEFAULT);
            UPDATE scores SET score = score + 5 WHERE bucket = 'a';
        `);

        expect(r.errors()).toEqual([]);
        expect(r.rows('scores').map((row) => row.score)).toEqual([15, 25, 30]);
        expect(r.rows('scores').map((row) => row.adjusted)).toEqual([30, 50, 60]);
        expect(r.warnings().some((entry) => /no WHERE/.test(entry.message))).toBe(false);
    });

    it('supports DEFAULT and time functions in UPDATE assignment expressions', () => {
        const r = exec(`
            CREATE TABLE audit_items (
                id INT PRIMARY KEY,
                status TEXT DEFAULT 'queued',
                touched_at TIMESTAMP
            );
            INSERT INTO audit_items VALUES (1, 'done', NULL);
            UPDATE audit_items SET status = DEFAULT, touched_at = NOW() WHERE id = 1;
        `);

        const row = r.rows('audit_items')[0];
        expect(row.status).toBe('queued');
        expect(row.touched_at).toMatch(/^\d{4}-\d{2}-\d{2}T/);
        expect(r.errors()).toEqual([]);
    });
});

describe('Data View SQL executor - DML subqueries', () => {
    it('supports INSERT INTO ... SELECT with scalar subqueries in the projection and WHERE IN subqueries', () => {
        const r = exec(`
            CREATE TABLE categories (id INT PRIMARY KEY, name TEXT);
            INSERT INTO categories VALUES (1, 'Books'), (2, 'Hardware'), (3, 'Archive');

            CREATE TABLE allowed_tags (tag TEXT PRIMARY KEY);
            INSERT INTO allowed_tags VALUES ('book'), ('tool');

            CREATE TABLE staging_products (
                id INT PRIMARY KEY,
                name TEXT,
                tag TEXT,
                price NUMERIC
            );
            INSERT INTO staging_products VALUES
                (10, 'SQL Patterns', 'book', 30),
                (11, 'Router', 'tool', 80),
                (12, 'Old Manual', 'legacy', 5);

            CREATE TABLE products (
                id INT PRIMARY KEY,
                category_id INT,
                name TEXT,
                price NUMERIC,
                label TEXT GENERATED ALWAYS AS (CONCAT(name, ':', category_id::TEXT)) STORED
            );

            INSERT INTO products (id, category_id, name, price)
            SELECT id,
                   (SELECT id FROM categories WHERE name = 'Books'),
                   name,
                   price
            FROM staging_products
            WHERE tag IN (SELECT tag FROM allowed_tags)
            ORDER BY id;
        `);

        expect(r.errors()).toEqual([]);
        expect(r.warnings()).toEqual([]);
        expect(r.rows('products')).toHaveLength(2);
        expect(r.rows('products').map((row) => [row.id, row.category_id, row.name, row.label])).toEqual([
            [10, 1, 'SQL Patterns', 'SQL Patterns:1'],
            [11, 1, 'Router', 'Router:1'],
        ]);
    });

    it('supports UPDATE SET with scalar subqueries and WHERE IN subqueries', () => {
        const r = exec(`
            CREATE TABLE categories (id INT PRIMARY KEY, name TEXT);
            INSERT INTO categories VALUES (1, 'Books'), (2, 'Hardware'), (3, 'Archive');

            CREATE TABLE price_adjustments (kind TEXT PRIMARY KEY, amount NUMERIC);
            INSERT INTO price_adjustments VALUES ('markup', 7), ('clearance', -3);

            CREATE TABLE products (
                id INT PRIMARY KEY,
                category_id INT,
                name TEXT,
                price NUMERIC,
                price_with_tax NUMERIC GENERATED ALWAYS AS (ROUND(price * 1.1, 2)) STORED
            );
            INSERT INTO products VALUES
                (10, 1, 'SQL Patterns', 30, DEFAULT),
                (11, 2, 'Router', 80, DEFAULT),
                (12, 3, 'Old Manual', 5, DEFAULT);

            UPDATE products
            SET category_id = (SELECT id FROM categories WHERE name = 'Archive'),
                price = price + (SELECT amount FROM price_adjustments WHERE kind = 'markup')
            WHERE category_id IN (SELECT id FROM categories WHERE name IN ('Books', 'Hardware'));
        `);

        expect(r.errors()).toEqual([]);
        expect(r.warnings()).toEqual([]);

        const rows = r.rows('products').sort((a, b) => a.id - b.id);
        expect(rows.map((row) => [row.id, row.category_id, row.price, row.price_with_tax])).toEqual([
            [10, 3, 37, 40.7],
            [11, 3, 87, 95.7],
            [12, 3, 5, 5.5],
        ]);
    });

    it('supports scalar subqueries in UPDATE WHERE comparisons', () => {
        const r = exec(`
            CREATE TABLE products (id INT PRIMARY KEY, name TEXT, price NUMERIC, bucket TEXT DEFAULT 'standard');
            INSERT INTO products VALUES
                (1, 'cheap', 10, DEFAULT),
                (2, 'mid', 20, DEFAULT),
                (3, 'premium', 40, DEFAULT);

            UPDATE products
            SET bucket = 'top'
            WHERE price >= (SELECT MAX(price) FROM products WHERE name <> 'premium');
        `);

        expect(r.errors()).toEqual([]);
        expect(r.rows('products').map((row) => [row.name, row.bucket])).toEqual([
            ['cheap', 'standard'],
            ['mid', 'top'],
            ['premium', 'top'],
        ]);
    });
});

describe('Data View SQL executor - production-style DDL plus DML', () => {
    it('executes typed identity tables, INSERT SELECT joins, generated totals, scalar UPDATE subqueries, and filtered deletes', () => {
        const r = exec(`
            CREATE TYPE order_status AS ENUM ('draft', 'review', 'paid', 'void');

            CREATE TABLE tenants (
                id INT GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 10) PRIMARY KEY,
                slug TEXT UNIQUE NOT NULL
            );
            INSERT INTO tenants (slug) VALUES ('acme'), ('globex');

            CREATE TABLE orders (
                id INT GENERATED ALWAYS AS IDENTITY (START WITH 1000 INCREMENT BY 5) PRIMARY KEY,
                tenant_id INT NOT NULL REFERENCES tenants(id),
                external_ref TEXT NOT NULL,
                status order_status NOT NULL DEFAULT 'draft',
                subtotal NUMERIC NOT NULL DEFAULT 0,
                discount NUMERIC DEFAULT 0,
                total NUMERIC GENERATED ALWAYS AS (GREATEST(subtotal - discount, 0)) STORED,
                UNIQUE (tenant_id, external_ref)
            );
            CREATE INDEX idx_orders_status ON orders (tenant_id, status);

            CREATE TABLE staging_orders (
                tenant_slug TEXT,
                external_ref TEXT,
                subtotal NUMERIC,
                discount NUMERIC
            );
            INSERT INTO staging_orders VALUES
                ('acme', 'A-1', 120, 20),
                ('acme', 'A-2', 35, 0),
                ('globex', 'G-1', 200, 50),
                ('skip', 'S-1', 999, 0);

            INSERT INTO orders (tenant_id, external_ref, subtotal, discount)
            SELECT t.id, s.external_ref, s.subtotal, s.discount
            FROM staging_orders s
            JOIN tenants t ON t.slug = s.tenant_slug
            WHERE s.subtotal BETWEEN 30 AND 250
            ORDER BY s.external_ref;

            CREATE TABLE adjustments (code TEXT PRIMARY KEY, amount NUMERIC);
            INSERT INTO adjustments VALUES ('rush', 15), ('coupon', 5);

            UPDATE orders
            SET subtotal = subtotal + (SELECT amount FROM adjustments WHERE code = 'rush'),
                status = 'review'
            WHERE tenant_id IN (SELECT id FROM tenants WHERE slug LIKE 'ac%')
              AND external_ref NOT LIKE '%2';

            DELETE FROM orders
            WHERE total NOT BETWEEN 50 AND 210 OR external_ref = 'A-2';
        `);

        expect(r.errors()).toEqual([]);
        expect(r.warnings()).toEqual([]);

        expect(r.rows('tenants').map((row) => [row.id, row.slug])).toEqual([
            [100, 'acme'],
            [110, 'globex'],
        ]);

        const rows = r.rows('orders').sort((a, b) => a.id - b.id);
        expect(rows.map((row) => [row.id, row.tenant_id, row.external_ref, row.status, row.subtotal, row.discount, row.total])).toEqual([
            [1000, 100, 'A-1', 'review', 135, 20, 115],
            [1010, 110, 'G-1', 'draft', 200, 50, 150],
        ]);

        const orders = r.table('orders');
        expect(orders.columns.find((column) => column.name === 'status').isEnum).toBe(true);
        expect(orders.indexes.map((index) => index.name)).toContain('idx_orders_status');
        expect(orders.compositeUniques).toEqual([{ name: null, cols: ['tenant_id', 'external_ref'] }]);
    });
});
