/** Runs a realistic cross-dialect production matrix through SQL-to-ERD conversion. */
import { describe, expect, it } from 'vitest';
import { sqlToErdSchema } from '@/lib/erdJsonSchema.js';

const tableByName = (schema, name) => schema.tables.find((table) => table.name.toLowerCase() === name.toLowerCase());
const colByName = (table, name) => table?.columns.find((column) => column.name.toLowerCase() === name.toLowerCase());
const errorsOnly = (schema) => (schema._parseErrors || []).filter((error) => error.severity === 'error');

function assertRenderable(schema) {
    expect(Array.isArray(schema.enums)).toBe(true);
    expect(Array.isArray(schema.composites)).toBe(true);
    expect(Array.isArray(schema.tables)).toBe(true);
    expect(Array.isArray(schema.relations)).toBe(true);
    schema.tables.forEach((table) => {
        expect(table.name).toBeTruthy();
        expect(Array.isArray(table.columns)).toBe(true);
        table.columns.forEach((column) => {
            expect(column.name).toBeTruthy();
            expect(typeof column.type).toBe('string');
            expect(Array.isArray(column.constraints)).toBe(true);
            expect(Array.isArray(column.extras)).toBe(true);
        });
    });
}

const sqliteCases = Array.from({ length: 24 }, (_, i) => {
    const suffix = i.toString().padStart(2, '0');
    const deleteAction = ['CASCADE', 'RESTRICT', 'SET NULL', 'NO ACTION'][i % 4];
    const generatedMode = i % 2 === 0 ? 'STORED' : 'VIRTUAL';
    return {
        name: `SQLite ERD matrix ${suffix}`,
        parent: `accounts_${suffix}`,
        child: `notes_${suffix}`,
        sql: `
            CREATE TABLE accounts_${suffix} (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                email TEXT NOT NULL UNIQUE,
                status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
            ) STRICT;

            CREATE TABLE notebooks_${suffix} (
                account_id INTEGER NOT NULL REFERENCES accounts_${suffix}(id) ON DELETE ${deleteAction},
                notebook_id TEXT NOT NULL,
                title TEXT NOT NULL COLLATE NOCASE,
                normalized_title TEXT GENERATED ALWAYS AS (lower(title)) ${generatedMode},
                PRIMARY KEY (account_id, notebook_id),
                CHECK (length(title) > 0)
            ) WITHOUT ROWID;

            CREATE TABLE notes_${suffix} (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                account_id INTEGER NOT NULL,
                notebook_id TEXT NOT NULL,
                body TEXT,
                is_archived INTEGER NOT NULL DEFAULT 0 CHECK (is_archived IN (0, 1)),
                FOREIGN KEY (account_id, notebook_id)
                    REFERENCES notebooks_${suffix}(account_id, notebook_id)
                    ON UPDATE CASCADE ON DELETE CASCADE
            ) STRICT;

            CREATE INDEX idx_notes_${suffix}_active
                ON notes_${suffix} (account_id, notebook_id)
                WHERE is_archived = 0;
            CREATE INDEX idx_notes_${suffix}_body ON notes_${suffix} (body);
        `,
    };
});

const postgresCases = Array.from({ length: 24 }, (_, i) => {
    const suffix = i.toString().padStart(2, '0');
    const identity = i % 2 === 0 ? 'GENERATED ALWAYS AS IDENTITY' : `GENERATED BY DEFAULT AS IDENTITY (START WITH ${i + 10})`;
    return {
        name: `PostgreSQL ERD matrix ${suffix}`,
        locations: `locations_${suffix}`,
        lots: `inventory_lots_${suffix}`,
        sql: `
            CREATE TYPE wh.stock_state_${suffix} AS ENUM ('pending', 'available', 'reserved', 'scrapped');
            CREATE TYPE wh.measurement_${suffix} AS (
                value NUMERIC(12, 4),
                unit TEXT
            );

            CREATE TABLE wh.locations_${suffix} (
                tenant_id BIGINT NOT NULL,
                location_id BIGINT ${identity},
                code TEXT NOT NULL,
                state wh.stock_state_${suffix} NOT NULL DEFAULT 'available',
                capacity wh.measurement_${suffix},
                attrs JSONB NOT NULL DEFAULT jsonb_build_object('zone', 'default'),
                search_key TEXT GENERATED ALWAYS AS (lower(code)) STORED,
                PRIMARY KEY (tenant_id, location_id),
                CONSTRAINT uq_locations_${suffix}_code UNIQUE (tenant_id, code),
                CONSTRAINT chk_locations_${suffix}_state CHECK (state <> 'scrapped' OR attrs IS NOT NULL)
            ) PARTITION BY HASH (tenant_id);

            CREATE TABLE wh.inventory_lots_${suffix} (
                tenant_id BIGINT NOT NULL,
                lot_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
                location_id BIGINT NOT NULL,
                sku TEXT NOT NULL,
                qty NUMERIC NOT NULL CHECK (qty >= 0),
                state wh.stock_state_${suffix} NOT NULL DEFAULT 'pending',
                PRIMARY KEY (tenant_id, lot_id),
                CONSTRAINT fk_lots_${suffix}_location
                    FOREIGN KEY (tenant_id, location_id)
                    REFERENCES wh.locations_${suffix}(tenant_id, location_id)
                    DEFERRABLE INITIALLY DEFERRED
            );

            CREATE INDEX idx_locations_${suffix}_state_code
                ON ONLY wh.locations_${suffix} USING btree (state, code)
                WHERE state <> 'scrapped';

            CREATE INDEX idx_lots_${suffix}_sku_expr
                ON wh.inventory_lots_${suffix} ((lower(sku)), state, qty DESC)
                WHERE qty > 0;
        `,
    };
});

const mysqlCases = Array.from({ length: 24 }, (_, i) => {
    const suffix = i.toString().padStart(2, '0');
    const generatedMode = i % 2 === 0 ? 'STORED' : 'VIRTUAL';
    return {
        name: `MySQL ERD matrix ${suffix}`,
        parent: `workspaces_${suffix}`,
        child: `memberships_${suffix}`,
        apiKeys: `api_keys_${suffix}`,
        sql: `
            CREATE TABLE \`workspaces_${suffix}\` (
                \`id\` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
                \`slug\` VARCHAR(64) NOT NULL,
                \`status\` ENUM('trial', 'active', 'locked') NOT NULL DEFAULT 'trial',
                \`flags\` SET('billing', 'sso', 'audit') DEFAULT 'billing',
                \`created_at\` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
                PRIMARY KEY (\`id\`),
                UNIQUE KEY \`uk_workspace_${suffix}_slug\` (\`slug\`),
                KEY \`idx_workspace_${suffix}_status_created\` (\`status\`, \`created_at\`)
            ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

            CREATE TABLE \`memberships_${suffix}\` (
                \`workspace_id\` BIGINT UNSIGNED NOT NULL,
                \`user_id\` BIGINT UNSIGNED NOT NULL,
                \`role\` ENUM('owner', 'admin', 'member', 'viewer') NOT NULL DEFAULT 'viewer',
                \`permissions\` SET('read', 'write', 'delete') NOT NULL DEFAULT 'read',
                PRIMARY KEY (\`workspace_id\`, \`user_id\`),
                CONSTRAINT \`fk_members_${suffix}_workspace\`
                    FOREIGN KEY (\`workspace_id\`) REFERENCES \`workspaces_${suffix}\` (\`id\`) ON DELETE CASCADE
            ) ENGINE=InnoDB;

            CREATE TABLE \`api_keys_${suffix}\` (
                \`workspace_id\` BIGINT UNSIGNED NOT NULL,
                \`key\` VARCHAR(128) NOT NULL,
                \`name\` VARCHAR(100) NOT NULL,
                \`name_lc\` VARCHAR(100) GENERATED ALWAYS AS (LOWER(\`name\`)) ${generatedMode},
                PRIMARY KEY (\`workspace_id\`, \`key\`),
                CONSTRAINT \`fk_keys_${suffix}_workspace\`
                    FOREIGN KEY (\`workspace_id\`) REFERENCES \`workspaces_${suffix}\` (\`id\`)
            ) ENGINE=InnoDB;

            CREATE UNIQUE INDEX \`uq_members_${suffix}_role\`
                ON \`memberships_${suffix}\` (\`workspace_id\`, \`role\`);
            CREATE FULLTEXT INDEX \`ft_keys_${suffix}_name\`
                ON \`api_keys_${suffix}\` (\`name\`);
        `,
    };
});

const mssqlCases = Array.from({ length: 24 }, (_, i) => {
    const suffix = i.toString().padStart(2, '0');
    const computedTail = i % 2 === 0 ? 'PERSISTED NOT NULL' : 'NOT NULL PERSISTED';
    return {
        name: `MSSQL ERD matrix ${suffix}`,
        parent: `Branches_${suffix}`,
        customers: `Customers_${suffix}`,
        accounts: `Accounts_${suffix}`,
        sql: `
            CREATE TABLE [dbo].[Branches_${suffix}] (
                [BranchID] INT IDENTITY(${10 + i}, ${i + 1}) NOT NULL,
                [Code] CHAR(6) NOT NULL,
                [Name] NVARCHAR(120) NOT NULL,
                CONSTRAINT [PK_Branches_${suffix}] PRIMARY KEY CLUSTERED ([BranchID]),
                CONSTRAINT [UQ_Branches_${suffix}_Code] UNIQUE NONCLUSTERED ([Code])
            );
            GO

            CREATE TABLE [dbo].[Customers_${suffix}] (
                [CustomerID] BIGINT IDENTITY(${1000 + i}, 1) NOT NULL,
                [BranchID] INT NOT NULL,
                [Email] NVARCHAR(320),
                [FirstName] NVARCHAR(80) NOT NULL,
                [LastName] NVARCHAR(80) NOT NULL,
                [FullName] AS ([FirstName] + N' ' + [LastName]) ${computedTail},
                CONSTRAINT [PK_Customers_${suffix}] PRIMARY KEY CLUSTERED ([CustomerID]),
                CONSTRAINT [UQ_Customers_${suffix}_Email] UNIQUE NONCLUSTERED ([Email]),
                CONSTRAINT [FK_Customers_${suffix}_Branch]
                    FOREIGN KEY ([BranchID]) REFERENCES [dbo].[Branches_${suffix}]([BranchID])
            );

            CREATE TABLE [dbo].[Accounts_${suffix}] (
                [AccountID] BIGINT IDENTITY(${5000 + i}, 10) NOT NULL,
                [CustomerID] BIGINT NOT NULL,
                [AccountNumber] NVARCHAR(34) NOT NULL,
                [Currency] CHAR(3) NOT NULL DEFAULT 'USD',
                [ClosedAt] DATETIME2 NULL,
                CONSTRAINT [PK_Accounts_${suffix}] PRIMARY KEY NONCLUSTERED ([AccountID]),
                CONSTRAINT [UQ_Accounts_${suffix}_Number] UNIQUE ([AccountNumber]),
                CONSTRAINT [FK_Accounts_${suffix}_Customer]
                    FOREIGN KEY ([CustomerID]) REFERENCES [dbo].[Customers_${suffix}]([CustomerID])
            );

            CREATE NONCLUSTERED INDEX [IX_Accounts_${suffix}_Customer]
                ON [dbo].[Accounts_${suffix}] ([CustomerID], [AccountNumber])
                INCLUDE ([Currency])
                WHERE [ClosedAt] IS NULL;
        `,
    };
});

describe.each([
    ['SQLite', sqliteCases],
    ['PostgreSQL', postgresCases],
    ['MySQL', mysqlCases],
    ['MSSQL', mssqlCases],
])('sqlToErd production matrix - %s', (_dialect, cases) => {
    it.each(cases)('$name', (testCase) => {
        const schema = sqlToErdSchema(testCase.sql);
        assertRenderable(schema);
        expect(errorsOnly(schema)).toEqual([]);

        if (testCase.name.startsWith('SQLite')) {
            const accounts = tableByName(schema, testCase.parent);
            const notes = tableByName(schema, testCase.child);
            expect(colByName(accounts, 'id').autoIncrement).toBe(true);
            expect(colByName(accounts, 'status').extras.some((extra) => extra.includes('CHECK'))).toBe(true);
            expect(colByName(notes, 'account_id').constraints).toContain('IDX');
            expect(colByName(notes, 'body').constraints).toContain('IDX');
            expect(schema.relations).toHaveLength(3);
        } else if (testCase.name.startsWith('PostgreSQL')) {
            const locations = tableByName(schema, testCase.locations);
            const lots = tableByName(schema, testCase.lots);
            expect(schema.enums[0].name).toMatch(/^stock_state_/);
            expect(schema.composites[0].name).toMatch(/^measurement_/);
            expect(colByName(locations, 'location_id').autoIncrement).toBe(true);
            expect(colByName(locations, 'capacity').type).toMatch(/^measurement_/);
            expect(colByName(locations, 'state').constraints).toContain('IDX');
            expect(colByName(lots, 'state').constraints).toContain('IDX');
            expect(schema.relations).toHaveLength(2);
        } else if (testCase.name.startsWith('MySQL')) {
            const workspaces = tableByName(schema, testCase.parent);
            const memberships = tableByName(schema, testCase.child);
            const apiKeys = tableByName(schema, testCase.apiKeys);
            expect(colByName(workspaces, 'id').autoIncrement).toBe(true);
            expect(colByName(workspaces, 'status').type).toBe('status_enum');
            expect(colByName(workspaces, 'flags').type).toBe('flags_set');
            expect(colByName(memberships, 'role').constraints).toContain('UQ');
            expect(colByName(apiKeys, 'name_lc').extras.some((extra) => /GENERATED ALWAYS AS/i.test(extra))).toBe(true);
            expect(colByName(apiKeys, 'name').constraints).toContain('IDX');
            expect(schema.relations).toHaveLength(2);
        } else {
            const branches = tableByName(schema, testCase.parent);
            const customers = tableByName(schema, testCase.customers);
            const accounts = tableByName(schema, testCase.accounts);
            expect(colByName(branches, 'BranchID').autoIncrement).toBe(true);
            expect(colByName(branches, 'Code').constraints).toContain('UQ');
            expect(colByName(customers, 'FullName').type).toBe('COMPUTED');
            expect(colByName(customers, 'FullName').constraints).toContain('NN');
            expect(colByName(accounts, 'CustomerID').constraints).toContain('IDX');
            expect(schema.relations).toHaveLength(2);
        }
    });
});
