const node = (id, shape, x, y, label, extra = {}) => ({
    id,
    type: 'erdDraftNode',
    position: { x, y },
    data: {
        shape,
        label,
        color: shape.includes('Attribute') || shape === 'attribute' ? '#98c45f' : shape.toLowerCase().includes('relationship') ? '#f5662b' : '#2389dd',
        description: '',
        ...extra,
    },
});

const edge = (id, source, target, sourceLabel = '', targetLabel = '', options = {}) => ({
    id,
    source,
    target,
    type: 'erdDraftEdge',
    data: {
        lineStyle: 'solid',
        routing: 'auto',
        lineCount: 'single',
        label: '',
        sourceLabel,
        targetLabel,
        sourceLabelPosition: null,
        targetLabelPosition: null,
        waypoints: [],
        ...options,
    },
});

